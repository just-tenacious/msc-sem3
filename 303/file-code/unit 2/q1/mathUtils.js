// Addition
const add = (a = 0, b = 0) => {
    return a + b;
};

// Subtraction
const subtract = (a = 0, b = 0) => {
    return a - b;
};

// Multiplication
const multiply = (a = 1, b = 1) => {
    return a * b;
};

// Division
const divide = (a = 1, b = 1) => {
    return a / b;
};

// Export all functions
export { add, subtract, multiply, divide };